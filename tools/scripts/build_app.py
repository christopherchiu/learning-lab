"""Rebuild the Learning Lab site + podcast feed inside the learning-lab repo.

Usage: python3 build_app.py <repo_dir>

Repo layout (GitHub Pages serves the repo root of `main`):
  library/config.json              {"title", "author", "description", "base_url"}
  library/progress.json            learner profile, concepts, suggested_next, feedback_log
  library/lessons/<slug>/meta.json title, summary, source_type, source_url, topics, created_at,
                                   duration_secs, audio_bytes, quiz, related
  library/lessons/<slug>/lesson.md the written lesson (blog post)
  library/lessons/<slug>/narration.txt  the spoken script
  audio/<slug>.mp3                 narrated episode
Generated by this script (commit them too):
  index.html app.js styles.css theme.css cover.png manifest.webmanifest .nojekyll  (from app_template)
  lessons.json                     index the reading site uses
  lessons/<slug>/lesson.html       rendered post
  feed.xml                         podcast RSS for Apple Podcasts / Apple Watch
Prints JSON listing every generated/changed path so you know what to commit.
"""
import json, os, shutil, subprocess, sys, html
from datetime import datetime, timezone
from email.utils import format_datetime

try:
    import markdown
except ImportError:
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "markdown"], check=True)
    import markdown

repo = os.path.abspath(sys.argv[1])
template = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app_template"))
lib = os.path.join(repo, "library")
written = []

for f in os.listdir(template):
    shutil.copy2(os.path.join(template, f), os.path.join(repo, f))
    written.append(f)
open(os.path.join(repo, ".nojekyll"), "w").close()
written.append(".nojekyll")

cfg = json.load(open(os.path.join(lib, "config.json")))
base = (cfg.get("base_url") or "").rstrip("/")
ldir = os.path.join(lib, "lessons")

lessons = []
for slug in sorted(os.listdir(ldir)) if os.path.isdir(ldir) else []:
    mp = os.path.join(ldir, slug, "meta.json")
    if not os.path.isfile(mp):
        continue
    meta = json.load(open(mp))
    meta["slug"] = slug
    md_path = os.path.join(ldir, slug, "lesson.md")
    if os.path.isfile(md_path):
        body = markdown.markdown(open(md_path).read(), extensions=["fenced_code", "tables", "sane_lists"])
        out_dir = os.path.join(repo, "lessons", slug)
        os.makedirs(out_dir, exist_ok=True)
        open(os.path.join(out_dir, "lesson.html"), "w").write(body)
        meta["html"] = f"lessons/{slug}/lesson.html"
        written.append(meta["html"])
    audio_rel = f"audio/{slug}.mp3"
    if os.path.isfile(os.path.join(repo, audio_rel)):
        meta["audio_bytes"] = os.path.getsize(os.path.join(repo, audio_rel))
    if meta.get("audio_bytes"):
        meta["audio"] = audio_rel
        meta["audio_url"] = f"{base}/{audio_rel}" if base else audio_rel
    lessons.append(meta)

lessons.sort(key=lambda m: m.get("created_at", ""), reverse=True)
progress = {}
pp = os.path.join(lib, "progress.json")
if os.path.isfile(pp):
    progress = json.load(open(pp))

json.dump({"title": cfg.get("title"), "base_url": base, "updated_at": datetime.now(timezone.utc).isoformat(),
           "lessons": lessons, "progress": progress}, open(os.path.join(repo, "lessons.json"), "w"), indent=2)
written.append("lessons.json")


def esc(s):
    return html.escape(str(s or ""), quote=True)


items = []
for m in lessons:
    if not m.get("audio_url") or not base:
        continue
    try:
        pub = format_datetime(datetime.fromisoformat(m["created_at"].replace("Z", "+00:00")))
    except Exception:
        pub = format_datetime(datetime.now(timezone.utc))
    desc = m.get("summary", "")
    if m.get("source_url"):
        desc += f"\n\nSource: {m['source_url']}"
    desc += f"\n\nRead the full lesson: {base}/#/{m['slug']}"
    items.append(f"""    <item>
      <title>{esc(m.get('title'))}</title>
      <description>{esc(desc)}</description>
      <guid isPermaLink="false">{esc(m['slug'])}</guid>
      <pubDate>{pub}</pubDate>
      <link>{esc(base)}/#/{esc(m['slug'])}</link>
      <enclosure url="{esc(m['audio_url'])}" length="{m.get('audio_bytes', 0)}" type="audio/mpeg"/>
      <itunes:duration>{int(m.get('duration_secs') or 0)}</itunes:duration>
      <itunes:explicit>false</itunes:explicit>
    </item>""")

feed = f"""<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:itunes="http://www.itunes.com/dtds/podcast-1.0.dtd" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>{esc(cfg.get('title'))}</title>
    <link>{esc(base)}</link>
    <atom:link href="{esc(base)}/feed.xml" rel="self" type="application/rss+xml"/>
    <description>{esc(cfg.get('description'))}</description>
    <language>en-us</language>
    <itunes:author>{esc(cfg.get('author'))}</itunes:author>
    <itunes:image href="{esc(base)}/cover.png"/>
    <itunes:category text="Education"/>
    <itunes:explicit>false</itunes:explicit>
    <itunes:type>episodic</itunes:type>
    <itunes:summary>{esc(cfg.get('description'))}</itunes:summary>
{chr(10).join(items)}
  </channel>
</rss>
"""
open(os.path.join(repo, "feed.xml"), "w").write(feed)
written.append("feed.xml")
print(json.dumps({"lessons": len(lessons), "feed_items": len(items), "base_url": base or None, "generated": written}))
